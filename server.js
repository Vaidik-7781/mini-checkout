// Zero-dependency static file server for the checkout page.
// Usage: node server.js [port]   (default 4173, or $PORT)
'use strict';
const http = require('http');
const fs = require('fs');
const path = require('path');

// PUBLIC_DIR lets scripts/mutation-check.js serve a deliberately broken copy.
const root = path.resolve(process.env.PUBLIC_DIR || path.join(__dirname, 'public'));
const port = Number(process.argv[2] || process.env.PORT || 4173);
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };

http.createServer((req, res) => {
  const urlPath = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  const file = path.normalize(path.join(root, urlPath === '/' ? 'index.html' : urlPath));
  if (!file.startsWith(root + path.sep)) { res.writeHead(403); return res.end('Forbidden'); }
  fs.readFile(file, (err, data) => {
    if (err) { res.writeHead(404, { 'Content-Type': 'text/plain' }); return res.end('Not found'); }
    res.writeHead(200, { 'Content-Type': types[path.extname(file)] || 'application/octet-stream', 'Cache-Control': 'no-store' });
    res.end(data);
  });
}).listen(port, () => console.log(`Mini Checkout running at http://localhost:${port}`));
